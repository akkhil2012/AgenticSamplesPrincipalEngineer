"""Audience-facing POC: evidence, protocol boundary, and reasoning are visible."""

import asyncio
import json
import os

import streamlit as st
from catalog import ROOT
from coordinator import recommend
from dotenv import load_dotenv
from llm import AgentFailure

load_dotenv(ROOT / ".env")
st.set_page_config(page_title="Procurement · MCP + A2A", page_icon="🔗", layout="wide")
st.title("Procurement desk: MCP + A2A")
st.write(
    "Give a buyer brief to an LLM coordinator. Watch it delegate research to another LLM agent, which uses MCP to read supplier evidence."
)
with st.sidebar:
    st.header("Connection status")
    st.write("API key:", "configured" if os.getenv("OPENAI_API_KEY") else "missing")
    st.write("Model:", os.getenv("OPENAI_MODEL", "gpt-4.1-mini"))
    st.caption(
        "Configure secrets in .env on the server. Both agents use that configuration. No mock fallback."
    )
    st.warning(
        "Example CSV contains fictional supplier quotes. Replace it with your supplier export for your own analysis."
    )
    st.caption(
        "Advisory only. Each run is independent. No orders are placed. Quote data and your request are sent to the configured LLM provider."
    )
    if st.button("Clear result"):
        st.session_state.pop("result", None)
        st.rerun()

brief, architecture = st.tabs(["Buyer brief & result", "Architecture & protocol guide"])
with architecture:
    st.graphviz_chart("""digraph {
      rankdir=LR; node [shape=box, style=rounded];
      UI [label="Buyer / Streamlit"];
      C [label="Coordinator agent\nLLM reasoning"];
      S [label="Sourcing agent\nIndependent LLM context"];
      M [label="MCP tool server"];
      D [label="Replaceable quote CSV"];
      UI -> C [label="buyer brief"];
      C -> S [label="A2A / HTTP\nAgent Card + message/send"];
      S -> M [label="MCP / stdio\ninitialize + tools/list + tools/call"];
      M -> D [label="query + exact cost"];
    }""")
    st.markdown("""
**A2A connects an agent to another agent.** The coordinator discovers the specialist's
Agent Card, sends a natural-language task through JSON-RPC, and receives a completed
task with a research artifact. The specialist controls its own LLM and tool use.

**MCP connects an agent to tools and data.** The specialist initializes a standard
MCP session, discovers tool schemas, and executes the tools selected by its LLM.
The MCP server calculates and retrieves facts; it does not act as an agent.

**The LLM chooses the work.** Tool selection, delegated wording, supplier comparison,
and the recommendation are generated by API calls. Python validates tool arguments,
performs exact arithmetic, bounds execution, and handles the protocols.

The trace shows observable protocol activity, not private chain-of-thought. Specialist
trace entries are carried back in the A2A artifact and grouped after task completion.
""")
with brief:
    with st.form("brief"):
        question = st.text_area(
            "What do you need to procure?",
            height=140,
            max_chars=6000,
            placeholder="We need 100 business laptops, 16GB RAM and 512GB storage, within USD 85,000. Delivery to the US in 12 days. Prefer EPEAT Gold. Compare options and explain compromises.",
        )
        run = st.form_submit_button(
            "Research & recommend", disabled=not os.getenv("OPENAI_API_KEY")
        )
    if run:
        st.session_state.pop("result", None)
        try:
            with st.spinner(
                "Agents are researching. Several LLM calls may take a few minutes…"
            ):
                st.session_state.result = asyncio.run(recommend(question))
        except AgentFailure as exc:
            st.error(str(exc))
        except Exception:  # noqa: BLE001 - redact external failures at the public boundary
            st.error(
                "The run failed. Check your provider configuration and specialist service."
            )
    if "result" in st.session_state:
        result = st.session_state.result
        st.subheader("Recommendation")
        st.markdown(result["answer"])
        st.subheader("Protocol evidence")
        trace = result["trace"]
        st.dataframe(
            [
                {"#": i + 1, "Protocol": e["protocol"], "Operation": e["operation"]}
                for i, e in enumerate(trace)
            ],
            hide_index=True,
            use_container_width=True,
        )
        with st.expander("Inspect messages, discovered tools, and task IDs"):
            st.json(trace)
        st.download_button(
            "Download run evidence",
            json.dumps(result, indent=2),
            file_name="procurement-run.json",
            mime="application/json",
        )
